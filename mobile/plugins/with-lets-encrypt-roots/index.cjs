// Expo config plugin: trusts Let's Encrypt's roots in addition to the system ones.
//
// Self-hosted Monetra servers usually use Let's Encrypt. Its newer ECDSA chains
// (YE* → Root YE → ISRG Root X2) only reach roots that Android ships from version
// 14, and Android 7.0 lacks even ISRG Root X1, so older phones reject the TLS
// handshake. Bundling the official roots as extra trust anchors keeps normal
// certificate validation (hostname, expiry, chain) and adds nothing else.
const fs = require('node:fs');
const path = require('node:path');
const { AndroidConfig, withAndroidManifest, withDangerousMod } = require('expo/config-plugins');

const certificatesDir = path.join(__dirname, 'certs');
const configName = 'network_security_config';
// Development builds still talk to http://10.0.2.2; release builds never allow cleartext.
const cleartextVariants = ['debug', 'debugOptimized'];

function certificateNames() {
  return fs.readdirSync(certificatesDir)
    .filter((file) => file.endsWith('.pem'))
    .map((file) => path.basename(file, '.pem'))
    .sort();
}

function networkSecurityConfig({ cleartextTrafficPermitted }) {
  const anchors = certificateNames().map((name) => `      <certificates src="@raw/${name}" />`).join('\n');
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-lets-encrypt-roots. Do not edit by hand. -->
<network-security-config>
  <base-config cleartextTrafficPermitted="${cleartextTrafficPermitted}">
    <trust-anchors>
      <certificates src="system" />
${anchors}
    </trust-anchors>
  </base-config>
</network-security-config>
`;
}

function writeFile(file, contents) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, contents);
}

/** Writes the raw certificates and network security configs under `<androidRoot>/app/src`. */
function writeAndroidResources(androidRoot) {
  const sourceSets = path.join(androidRoot, 'app', 'src');
  for (const name of certificateNames()) {
    writeFile(path.join(sourceSets, 'main', 'res', 'raw', `${name}.pem`), fs.readFileSync(path.join(certificatesDir, `${name}.pem`)));
  }
  writeFile(path.join(sourceSets, 'main', 'res', 'xml', `${configName}.xml`), networkSecurityConfig({ cleartextTrafficPermitted: false }));
  for (const variant of cleartextVariants) {
    writeFile(path.join(sourceSets, variant, 'res', 'xml', `${configName}.xml`), networkSecurityConfig({ cleartextTrafficPermitted: true }));
  }
}

const withLetsEncryptRoots = (config) => {
  config = withDangerousMod(config, ['android', async (modConfig) => {
    writeAndroidResources(modConfig.modRequest.platformProjectRoot);
    return modConfig;
  }]);
  return withAndroidManifest(config, (modConfig) => {
    const application = AndroidConfig.Manifest.getMainApplicationOrThrow(modConfig.modResults);
    application.$['android:networkSecurityConfig'] = `@xml/${configName}`;
    return modConfig;
  });
};

module.exports = withLetsEncryptRoots;
module.exports.certificateNames = certificateNames;
module.exports.networkSecurityConfig = networkSecurityConfig;
module.exports.writeAndroidResources = writeAndroidResources;
